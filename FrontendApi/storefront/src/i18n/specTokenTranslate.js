function accentInsensitivePattern(fr) {
  return fr
    .split('')
    .map((c) => {
      if (c === ' ') return '\\s+';
      const base = c.normalize('NFD').replace(/\p{M}/gu, '');
      if (/[a-z0-9]/i.test(base)) return `${base}\\p{M}*`;
      return c.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    })
    .join('');
}

function applyTokens(text, pairs) {
  let result = String(text ?? '');
  const sorted = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [fr, tr] of sorted) {
    if (!norm(result).includes(norm(fr))) continue;
    const re = new RegExp(accentInsensitivePattern(fr), 'giu');
    result = result.replace(re, tr);
  }
  return result;
}

/**
 * Traduit un libellé ou une valeur de fiche technique (FR → EN / AR).
 */
export function translateSpecText(text, lng) {
  if (!text || lng === 'fr') return String(text ?? '');
  const pairs = lng === 'ar' ? FR_AR : FR_EN;
  return applyTokens(text, pairs);
}
